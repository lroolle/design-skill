#!/usr/bin/env node
// deck.mjs -- the deck the page deals from is the deck the CLI deals from.
//
// Reads skills/design-skill/decks/worlds/*.md and decks/compositions/*.md (the same
// frontmatter scripts/roll.mjs reads) and writes site/deck.js, a plain
// script that defines window.DESIGN_SKILL_DECK. deal.js ports the roll
// to the browser; with this file the same key gives the same hand on the
// page and in `node scripts/roll.mjs`.
//
//   node site/deck.mjs            write site/deck.js
//   node site/deck.mjs --check    exit 1 if site/deck.js is out of date
//
// Deterministic output: no dates, stable key order, so validate.sh can
// diff a regeneration against the committed file.

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const skill = join(here, '..', 'skills', 'design-skill');
const out = join(here, 'deck.js');

const worlds = readDeck(join(skill, 'decks', 'worlds')).map(w => ({
  id: w.id, name: w.name, tier: w.tier,
  modes: w.modes, platforms: w.platforms, rating: w.rating,
}));
const stagings = readDeck(join(skill, 'decks', 'compositions'));

const body = '/* generated by site/deck.mjs from skills/design-skill/decks/worlds and decks/compositions -- do not edit by hand */\n'
  + 'window.DESIGN_SKILL_DECK = ' + JSON.stringify({ worlds, stagings: stagings.length }, null, 0) + ';\n';

if (process.argv.includes('--check')) {
  const have = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (have !== body) { console.error('site/deck.js is out of date: run node site/deck.mjs'); process.exit(1); }
  console.log(`site/deck.js in sync: ${worlds.length} worlds, ${stagings.length} stagings`);
  process.exit(0);
}
writeFileSync(out, body);
console.log(`wrote ${out}: ${worlds.length} worlds, ${stagings.length} stagings`);

// ---- same parser as scripts/roll.mjs, so the two never disagree ----
function readDeck(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter(f => f.endsWith('.md') && !f.startsWith('_') && f !== 'README.md').sort().map(f => {
    const fm = frontmatter(readFileSync(join(dir, f), 'utf8'));
    return { ...fm, id: fm.id || f.replace(/\.md$/, ''), name: fm.name || fm.id || f, rating: parseInt(fm.rating || '2', 10) };
  });
}
function frontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---/);
  const o = {};
  if (!m) return o;
  for (const line of m[1].split('\n')) {
    const mm = line.match(/^([a-zA-Z_-]+):\s*(.*?)\s*(#.*)?$/);
    if (!mm) continue;
    let v = mm[2].trim();
    if (v.startsWith('[') && v.endsWith(']')) v = v.slice(1, -1).split(',').map(s => s.trim()).filter(Boolean);
    o[mm[1]] = v;
  }
  return o;
}
